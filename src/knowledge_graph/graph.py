class IngredientKnowledgeGraph:
    """
    Provenance-Aware Skincare Ingredient Knowledge Graph for DermaSense.
    
    Graph Topology:
    - Nodes:
        * Ingredient (canonical active chemicals)
        * Synonym (INCI aliases and common trade names)
        * CosmeticFunction (biochemical cellular mechanisms)
        * SkinConcern (dermatological target vector)
        * EvidenceSource (peer-reviewed medical journal publications with PMIDs)
        * CautionWarning (clinical contraindications and layering precautions)
    - Edges:
        * HAS_SYNONYM (Ingredient -> Synonym)
        * HAS_FUNCTION (Ingredient -> CosmeticFunction)
        * TARGETS_CONCERN (CosmeticFunction -> SkinConcern)
        * EVIDENCE_SUPPORTED_BY (Ingredient -> EvidenceSource)
        * HAS_DOCUMENTED_CAUTION (Ingredient -> CautionWarning)
    """

    _instance = None

    def __init__(self):
        self.graph = nx.DiGraph()
        self.synonym_lookup: Dict[str, str] = {}
        self._build_knowledge_graph()

    @classmethod
    def get_instance(cls):
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def _build_knowledge_graph(self):
        """Builds graph nodes, relationship edges, and alias lookup indices."""
        # 1. Add Skin Concerns from existing ontology
        for concern in SKIN_BENEFITS_MAP.keys():
            self.graph.add_node(concern, node_type="SkinConcern", name=concern)

        # 2. Add Canonical Ingredients from existing ontology + functions map
        canonical_ingredients: Set[str] = set()
        for concern, actives in SKIN_BENEFITS_MAP.items():
            for act in actives:
                canonical_ingredients.add(act.lower().strip())
        for act in INGREDIENT_FUNCTIONS.keys():
            canonical_ingredients.add(act.lower().strip())

        for act in canonical_ingredients:
            desc = INGREDIENT_DESCRIPTIONS.get(act, "Biochemically active cosmetic compound supporting targeted skin health.")
            self.graph.add_node(act, node_type="Ingredient", name=act.title(), description=desc)
            self.synonym_lookup[act] = act

        # 3. Add Synonyms and Edges
        for canonical, aliases in INGREDIENT_SYNONYMS.items():
            canonical_clean = canonical.lower().strip()
            if not self.graph.has_node(canonical_clean):
                self.graph.add_node(canonical_clean, node_type="Ingredient", name=canonical.title())
            for alias in aliases:
                alias_clean = alias.lower().strip()
                self.graph.add_node(alias_clean, node_type="Synonym", name=alias.title())
                self.graph.add_edge(canonical_clean, alias_clean, relationship="HAS_SYNONYM")
                self.graph.add_edge(alias_clean, canonical_clean, relationship="SYNONYM_OF")
                self.synonym_lookup[alias_clean] = canonical_clean

        # 4. Add Cosmetic Functions and Concern Linkages
        for ingredient, funcs in INGREDIENT_FUNCTIONS.items():
            ing_clean = ingredient.lower().strip()
            for func_id, func_desc in funcs:
                if not self.graph.has_node(func_id):
                    self.graph.add_node(func_id, node_type="CosmeticFunction", id=func_id, description=func_desc)
                self.graph.add_edge(ing_clean, func_id, relationship="HAS_FUNCTION", mechanism=func_desc)

                # Link function to target skin concerns
                target_concerns = FUNCTION_TO_CONCERN.get(func_id, [])
                for concern in target_concerns:
                    if self.graph.has_node(concern):
                        self.graph.add_edge(func_id, concern, relationship="TARGETS_CONCERN")

        # Connect ontology actives directly to concerns as baseline verification
        for concern, actives in SKIN_BENEFITS_MAP.items():
            for act in actives:
                act_clean = act.lower().strip()
                if self.graph.has_node(act_clean):
                    self.graph.add_edge(act_clean, concern, relationship="ONTOLOGY_MATCHES_CONCERN")

        # 5. Add Peer-Reviewed Evidence Sources
        for ingredient, evidence in EVIDENCE_SOURCES.items():
            ing_clean = ingredient.lower().strip()
            cit_id = evidence['citation_id']
            self.graph.add_node(
                cit_id,
                node_type="EvidenceSource",
                citation_id=cit_id,
                authors=evidence['authors'],
                year=evidence['year'],
                journal=evidence['journal'],
                title=evidence['title'],
                finding=evidence['key_finding']
            )
            self.graph.add_edge(ing_clean, cit_id, relationship="EVIDENCE_SUPPORTED_BY", citation_id=cit_id)

        # 6. Add Contraindications and Warnings
        for rule in CONTRAINDICATION_RULES:
            rule_id = rule['id']
            self.graph.add_node(
                rule_id,
                node_type="CautionWarning",
                title=rule['title'],
                level=rule['caution_level'],
                mechanism=rule['mechanism'],
                recommendation=rule['recommendation']
            )
            for act in rule['actives']:
                act_clean = act.lower().strip()
                if self.graph.has_node(act_clean):
                    self.graph.add_edge(act_clean, rule_id, relationship="HAS_DOCUMENTED_CAUTION")

        print(f"✓ Ingredient Knowledge Graph built: {self.graph.number_of_nodes()} nodes, {self.graph.number_of_edges()} edges.")

    def resolve_ingredient_entity(self, text: str) -> Optional[str]:
        """
        Normalizes aliases, chemical synonyms, or INCI tokens to their canonical ingredient name.
        """
        if not text:
            return None
        cleaned = text.lower().strip()
        # Direct lookup
        if cleaned in self.synonym_lookup:
            return self.synonym_lookup[cleaned]
        # Regex word boundary matching against known synonyms
        for alias, canonical in self.synonym_lookup.items():
            if re.search(r'\b' + re.escape(alias) + r'\b', cleaned):
                return canonical
        return None

    def get_all_ingredients(self) -> List[str]:
        """Returns sorted list of all canonical ingredient names in the knowledge graph."""
        return sorted(list(set(self.synonym_lookup.values())))

    def get_ingredient_provenance(self, ingredient_name: str) -> Optional[Dict[str, Any]]:
        """
        Retrieves complete knowledge graph provenance for a specific chemical active.
        """
        canonical = self.resolve_ingredient_entity(ingredient_name)
        if not canonical or not self.graph.has_node(canonical):
            return None

        node_data = self.graph.nodes[canonical]
        
        # Outgoing edges
        functions = []
        concerns = set()
        cautions = []
        evidence = []
        synonyms = []

        for _, target, data in self.graph.out_edges(canonical, data=True):
            rel = data.get('relationship')
            target_data = self.graph.nodes[target]
            target_type = target_data.get('node_type')

            if rel == 'HAS_FUNCTION':
                func_id = target_data.get('id')
                functions.append({
                    'function_id': func_id,
                    'mechanism': target_data.get('description')
                })
                # Check functions to concerns
                for _, concern_target, f_data in self.graph.out_edges(target, data=True):
                    if f_data.get('relationship') == 'TARGETS_CONCERN':
                        concerns.add(concern_target)
            elif rel == 'ONTOLOGY_MATCHES_CONCERN':
                concerns.add(target)
            elif rel == 'EVIDENCE_SUPPORTED_BY':
                evidence.append({
                    'citation_id': target_data.get('citation_id'),
                    'authors': target_data.get('authors'),
                    'year': target_data.get('year'),
                    'journal': target_data.get('journal'),
                    'title': target_data.get('title'),
                    'finding': target_data.get('finding')
                })
            elif rel == 'HAS_DOCUMENTED_CAUTION':
                cautions.append({
                    'rule_id': target,
                    'title': target_data.get('title'),
                    'level': target_data.get('level'),
                    'mechanism': target_data.get('mechanism'),
                    'recommendation': target_data.get('recommendation')
                })
            elif rel == 'HAS_SYNONYM':
                synonyms.append(target_data.get('name', target))

        return {
            'canonical_name': canonical,
            'display_name': node_data.get('name', canonical.title()),
            'description': node_data.get('description', ''),
            'synonyms': synonyms,
            'cosmetic_functions': functions,
            'targeted_concerns': sorted(list(concerns)),
            'evidence_citations': evidence,
            'documented_cautions': cautions
        }

    def trace_recommendation_reasoning(
        self,
        product_actives: List[str],
        user_concerns: List[str]
    ) -> List[Dict[str, Any]]:
        """
        Traces verifiable provenance reasoning chains for candidate product actives:
        User Stated Concern ──> Cosmetic Function ──> Active Chemical ──> Scientific Citation.
        """
        reasoning_paths = []
        user_concerns_clean = [c.strip() for c in user_concerns if c]

        for act in product_actives:
            canonical = self.resolve_ingredient_entity(act)
            if not canonical:
                continue

            prov = self.get_ingredient_provenance(canonical)
            if not prov:
                continue

            # Find intersection between user concerns and ingredient targeted concerns
            matching_concerns = [c for c in user_concerns_clean if c in prov['targeted_concerns']]
            
            # Extract relevant functions
            matching_functions = []
            for func in prov['cosmetic_functions']:
                func_id = func['function_id']
                func_concerns = FUNCTION_TO_CONCERN.get(func_id, [])
                if any(mc in func_concerns for mc in matching_concerns):
                    matching_functions.append(func['mechanism'])

            path = {
                'active_ingredient': prov['display_name'],
                'canonical_name': canonical,
                'is_ontology_verified': True,
                'addressed_concerns': matching_concerns,
                'cellular_mechanisms': matching_functions or [prov['description']],
                'citations': prov['evidence_citations']
            }
            reasoning_paths.append(path)

        return reasoning_paths

    def detect_contraindications(self, product_actives: List[str]) -> List[Dict[str, Any]]:
        """
        Analyzes a list of active ingredients within a single product or combined routine
        to detect chemical incompatibilities or usage precautions.
        """
        detected_cautions = []
        canonical_actives = set()
        for act in product_actives:
            c = self.resolve_ingredient_entity(act)
            if c:
                canonical_actives.add(c)

        for rule in CONTRAINDICATION_RULES:
            rule_actives = set(rule['actives'])
            # Check if all or subset of rule actives are present in the candidate formulation
            if rule_actives.issubset(canonical_actives):
                detected_cautions.append({
                    'rule_id': rule['id'],
                    'title': rule['title'],
                    'severity': rule['caution_level'],
                    'colliding_actives': list(rule_actives),
                    'mechanism': rule['mechanism'],
                    'recommendation': rule['recommendation']
                })

        return detected_cautions

    def get_graph_evidence_card(self, product_row: Any, user_concerns: List[str]) -> Dict[str, Any]:
        """
        Produces a complete graph evidence summary dictionary ready for presentation
        in recommendation cards, modals, or comparison panels.
        """
        actives_raw = product_row.get('matched_actives') if isinstance(product_row, dict) else product_row['matched_actives']
        if isinstance(actives_raw, str):
            try:
                actives = json.loads(actives_raw)
            except Exception:
                actives = []
        elif isinstance(actives_raw, list):
            actives = actives_raw
        else:
            actives = []

        reasoning_paths = self.trace_recommendation_reasoning(actives, user_concerns)
        contraindications = self.detect_contraindications(actives)

        total_citations = sum(len(p['citations']) for p in reasoning_paths)
        evidence_grounding_score = min(1.0, 0.4 * len(reasoning_paths) + 0.3 * min(total_citations, 2))

        return {
            'has_graph_evidence': len(reasoning_paths) > 0,
            'grounding_score': round(evidence_grounding_score, 2),
            'verified_paths_count': len(reasoning_paths),
            'reasoning_paths': reasoning_paths,
            'contraindications': contraindications
        }


